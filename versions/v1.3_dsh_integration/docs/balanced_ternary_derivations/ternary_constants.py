class BalancedTernaryDigit:
    """A single balanced ternary digit: -1, 0, or +1"""
    
    SYMBOLS = {-1: 'Z', 0: '0', 1: '1'}
    
    def __init__(self, value: int):
        if value not in (-1, 0, 1):
            raise ValueError(f"Balanced ternary digit must be -1, 0, or 1, got {value}")
        self.value = value
    
    def __repr__(self):
        return self.SYMBOLS[self.value]
    
    def __add__(self, other):
        """Balanced ternary addition (with carry)"""
        if isinstance(other, BalancedTernaryDigit):
            s = self.value + other.value
            if s == 2:
                return BalancedTernaryDigit(-1), BalancedTernaryDigit(1)  # carry +1
            elif s == -2:
                return BalancedTernaryDigit(1), BalancedTernaryDigit(-1)  # carry -1
            elif s == 3:
                return BalancedTernaryDigit(0), BalancedTernaryDigit(1)
            elif s == -3:
                return BalancedTernaryDigit(0), BalancedTernaryDigit(-1)
            else:
                return BalancedTernaryDigit(s), BalancedTernaryDigit(0)
        return NotImplemented
    
    def negate(self):
        """Negation: flip all digits. Balanced ternary makes this trivial."""
        return BalancedTernaryDigit(-self.value)
    
    def to_int(self):
        return self.value


class BalancedTernary:
    """A balanced ternary number represented as a list of digits (LSB first)"""
    
    def __init__(self, digits: List[int] = None):
        if digits is None:
            digits = [0]
        self.digits = [BalancedTernaryDigit(d) for d in digits]
        self._normalize()
    
    def _normalize(self):
        """Remove leading zeros"""
        while len(self.digits) > 1 and self.digits[-1].value == 0:
            self.digits.pop()
    
    @classmethod
    def from_int(cls, n: int) -> 'BalancedTernary':
        """Convert integer to balanced ternary"""
        if n == 0:
            return cls([0])
        digits = []
        while n != 0:
            remainder = n % 3
            if remainder == 2:
                remainder = -1
                n = n // 3 + 1
            else:
                n = n // 3
            digits.append(remainder)
        return cls(digits)
    
    def to_int(self) -> int:
        """Convert back to integer"""
        result = 0
        for i, digit in enumerate(self.digits):
            result += digit.value * (3 ** i)
        return result
    
    def __repr__(self):
        return ''.join(str(d) for d in reversed(self.digits))
    
    def negate(self) -> 'BalancedTernary':
        """Negate: flip all digits. This is trivial in balanced ternary!"""
        return BalancedTernary([-d.value for d in self.digits])


